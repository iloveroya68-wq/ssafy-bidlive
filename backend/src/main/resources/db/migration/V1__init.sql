                               deal_shipping_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               deal_id                BIGINT NOT NULL UNIQUE,
                               recipient_name         VARCHAR(50),
                               recipient_phone        VARCHAR(30),
                               postal_code            VARCHAR(20),
                               address                VARCHAR(255),
                               address_detail         VARCHAR(255),
                               carrier                VARCHAR(50),
