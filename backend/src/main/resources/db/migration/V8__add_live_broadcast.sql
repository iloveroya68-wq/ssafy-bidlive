-- LIVE-01/LIVE-02가 사용하는 방 단위 방송 상태 기록.
--
-- auction_room에도 status와 ended_at이 있지만 그 테이블과 판매자 정보(product.seller_id)는
-- auction 도메인이 소유한다. auction 도메인 구현이 아직 없어 media 도메인이 방송 개시자와
-- 방송 상태만 별도로 보관하며, auction의 공개 계약이 생기면 이 테이블은 제거 대상이다.

CREATE TABLE live_broadcast (
                                live_broadcast_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                room_id            VARCHAR(100) NOT NULL UNIQUE,
                                broadcaster_id     BIGINT NOT NULL,
                                status             VARCHAR(20) NOT NULL,
                                started_at         TIMESTAMPTZ NOT NULL,
                                ended_at           TIMESTAMPTZ,
                                created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_live_broadcast_broadcaster
                                    FOREIGN KEY (broadcaster_id)
                                        REFERENCES member (member_id)
                                        ON DELETE RESTRICT,
                                CONSTRAINT ck_live_broadcast_status
                                    CHECK (status IN ('LIVE', 'ENDED')),
                                CONSTRAINT ck_live_broadcast_ended_at
                                    CHECK (
                                        (status = 'ENDED' AND ended_at IS NOT NULL)
                                            OR
                                        (status = 'LIVE' AND ended_at IS NULL)
                                        ),
                                CONSTRAINT ck_live_broadcast_time_order
                                    CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TRIGGER trg_live_broadcast_updated_at
    BEFORE UPDATE ON live_broadcast
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX idx_live_broadcast_status
    ON live_broadcast (status);
