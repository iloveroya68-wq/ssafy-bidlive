CREATE TABLE deal (
                      deal_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      auction_result_id   BIGINT NOT NULL UNIQUE,
                      seller_member_id    BIGINT NOT NULL,
                      buyer_member_id     BIGINT NOT NULL,
                      final_price         BIGINT NOT NULL,
                      escrow_amount       BIGINT NOT NULL,
                      escrow_status       VARCHAR(20) NOT NULL,
                      deal_status         VARCHAR(30) NOT NULL,
                      snapshot_image_url  VARCHAR(500),
                      created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                      completed_at        TIMESTAMPTZ,
                      cancelled_at        TIMESTAMPTZ,

                      CONSTRAINT fk_deal_auction_result
                          FOREIGN KEY (auction_result_id)
                              REFERENCES auction_result (auction_result_id)
                              ON DELETE RESTRICT,
                      CONSTRAINT fk_deal_seller
                          FOREIGN KEY (seller_member_id)
                              REFERENCES member (member_id)
                              ON DELETE RESTRICT,
                      CONSTRAINT fk_deal_buyer
                          FOREIGN KEY (buyer_member_id)
                              REFERENCES member (member_id)
                              ON DELETE RESTRICT,
                      CONSTRAINT ck_deal_final_price
                          CHECK (final_price > 0),
                      CONSTRAINT ck_deal_escrow_amount
                          CHECK (escrow_amount >= 0),
                      CONSTRAINT ck_deal_different_parties
                          CHECK (seller_member_id <> buyer_member_id),
                      CONSTRAINT ck_deal_terminal_times
                          CHECK (NOT (completed_at IS NOT NULL AND cancelled_at IS NOT NULL))
);

CREATE INDEX idx_deal_seller_history
    ON deal (seller_member_id, created_at DESC);

CREATE INDEX idx_deal_buyer_history
    ON deal (buyer_member_id, created_at DESC);

CREATE INDEX idx_deal_status
    ON deal (deal_status, created_at);

