-- =========================================================
-- Auction / Prediction result
-- =========================================================

CREATE TABLE auction_result (
                                auction_result_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                auction_room_id            BIGINT NOT NULL UNIQUE,
                                result_status              VARCHAR(20) NOT NULL,
                                termination_reason         VARCHAR(30) NOT NULL,
                                winner_participant_id      BIGINT,
                                winning_bid_id             BIGINT,
                                highest_bid_amount         BIGINT,
                                second_highest_bid_amount  BIGINT,
                                final_price                BIGINT,
                                valid_bidder_count         INT NOT NULL,
                                total_bid_count            INT NOT NULL,
                                created_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_auction_result_room
                                    FOREIGN KEY (auction_room_id)
                                        REFERENCES auction_room (auction_room_id)
                                        ON DELETE RESTRICT,
                                CONSTRAINT fk_auction_result_winner
                                    FOREIGN KEY (winner_participant_id)
                                        REFERENCES auction_participant (auction_participant_id)
                                        ON DELETE RESTRICT,
                                CONSTRAINT fk_auction_result_winning_bid
                                    FOREIGN KEY (winning_bid_id)
                                        REFERENCES bid (bid_id)
                                        ON DELETE RESTRICT,
                                CONSTRAINT ck_auction_result_status
                                    CHECK (result_status IN ('SOLD', 'NO_SALE', 'CANCELLED')),
                                CONSTRAINT ck_auction_result_counts
                                    CHECK (
                                        valid_bidder_count >= 0
                                            AND total_bid_count >= 0
                                            AND total_bid_count >= valid_bidder_count
                                        ),
                                CONSTRAINT ck_auction_result_amounts
                                    CHECK (
                                        (highest_bid_amount IS NULL OR highest_bid_amount > 0)
                                            AND (second_highest_bid_amount IS NULL OR second_highest_bid_amount > 0)
                                            AND (final_price IS NULL OR final_price > 0)
                                        ),
                                CONSTRAINT ck_auction_result_status_fields
                                    CHECK (
                                        (
                                            result_status = 'SOLD'
                                                AND winner_participant_id IS NOT NULL
                                                AND winning_bid_id IS NOT NULL
                                                AND highest_bid_amount IS NOT NULL
                                                AND final_price IS NOT NULL
                                            )
                                            OR
                                        (
                                            result_status IN ('NO_SALE', 'CANCELLED')
                                                AND winner_participant_id IS NULL
                                                AND winning_bid_id IS NULL
                                                AND final_price IS NULL
                                            )
                                        )
);

CREATE UNIQUE INDEX uq_auction_result_winner_participant
    ON auction_result (winner_participant_id)
    WHERE winner_participant_id IS NOT NULL;

CREATE UNIQUE INDEX uq_auction_result_winning_bid
    ON auction_result (winning_bid_id)
    WHERE winning_bid_id IS NOT NULL;

CREATE TABLE prediction_result (
                                   prediction_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   prediction_id        BIGINT NOT NULL UNIQUE,
                                   auction_result_id    BIGINT NOT NULL,
                                   result_status        VARCHAR(20) NOT NULL,
                                   error_rate           NUMERIC(8, 6),
                                   reward_multiplier    NUMERIC(5, 2) NOT NULL,
                                   payout_amount        BIGINT NOT NULL,
                                   created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   CONSTRAINT fk_prediction_result_prediction
                                       FOREIGN KEY (prediction_id)
                                           REFERENCES prediction (prediction_id)
                                           ON DELETE RESTRICT,
                                   CONSTRAINT fk_prediction_result_auction_result
                                       FOREIGN KEY (auction_result_id)
                                           REFERENCES auction_result (auction_result_id)
                                           ON DELETE RESTRICT,
                                   CONSTRAINT ck_prediction_result_error_rate
                                       CHECK (error_rate IS NULL OR error_rate >= 0),
                                   CONSTRAINT ck_prediction_result_multiplier
                                       CHECK (reward_multiplier IN (0, 1, 3, 5)),
                                   CONSTRAINT ck_prediction_result_payout
                                       CHECK (payout_amount >= 0)
);

CREATE INDEX idx_prediction_result_auction_result
    ON prediction_result (auction_result_id);

