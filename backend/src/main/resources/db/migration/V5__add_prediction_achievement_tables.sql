-- Prediction achievement read model for PRED-04.
-- Aggregate counts and point totals remain derived from prediction and prediction_result.
-- Application invariant: prediction_badge.member_id must own the prediction referenced by
-- earned_prediction_result_id.

CREATE TABLE prediction_achievement (
                                        prediction_achievement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        member_id                 BIGINT NOT NULL,
                                        grade_code                VARCHAR(30) NOT NULL,
                                        grade_score               BIGINT NOT NULL DEFAULT 0,
                                        created_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                        updated_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                        CONSTRAINT fk_prediction_achievement_member
                                            FOREIGN KEY (member_id)
                                                REFERENCES member (member_id)
                                                ON DELETE RESTRICT,
                                        CONSTRAINT uq_prediction_achievement_member
                                            UNIQUE (member_id),
                                        CONSTRAINT ck_prediction_achievement_grade_code
                                            CHECK (length(btrim(grade_code)) > 0),
                                        CONSTRAINT ck_prediction_achievement_grade_score
                                            CHECK (grade_score >= 0)
);

CREATE TRIGGER trg_prediction_achievement_updated_at
    BEFORE UPDATE ON prediction_achievement
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TABLE prediction_badge (
                                  prediction_badge_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  member_id                   BIGINT NOT NULL,
                                  badge_code                  VARCHAR(50) NOT NULL,
                                  earned_prediction_result_id BIGINT NOT NULL,
                                  earned_at                   TIMESTAMPTZ NOT NULL,

                                  CONSTRAINT fk_prediction_badge_member
                                      FOREIGN KEY (member_id)
                                          REFERENCES member (member_id)
                                          ON DELETE RESTRICT,
                                  CONSTRAINT fk_prediction_badge_result
                                      FOREIGN KEY (earned_prediction_result_id)
                                          REFERENCES prediction_result (prediction_result_id)
                                          ON DELETE RESTRICT,
                                  CONSTRAINT uq_prediction_badge_member_code
                                      UNIQUE (member_id, badge_code),
                                  CONSTRAINT ck_prediction_badge_code
                                      CHECK (length(btrim(badge_code)) > 0)
);

CREATE INDEX idx_prediction_badge_member_earned
    ON prediction_badge (member_id, earned_at DESC);

COMMENT ON TABLE prediction_achievement IS '회원별 현재 예측 명예 등급과 점수';
COMMENT ON TABLE prediction_badge IS '회원별 예측 명예 뱃지 획득 이력';
