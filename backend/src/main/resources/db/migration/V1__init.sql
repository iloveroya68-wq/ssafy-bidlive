CREATE TABLE auction_room (
                              auction_room_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              product_id           BIGINT NOT NULL UNIQUE,
                              reserve_price        BIGINT NOT NULL,
                              duration_minutes     INT NOT NULL,
                              start_type           VARCHAR(20) NOT NULL,
                              scheduled_at         TIMESTAMPTZ,
                              started_at           TIMESTAMPTZ,
                              ends_at              TIMESTAMPTZ,
                              ended_at             TIMESTAMPTZ,
                              extension_count      INT NOT NULL DEFAULT 0,
                              status               VARCHAR(30) NOT NULL,
                              openvidu_session_id  VARCHAR(100),
                              created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_auction_room_product
                                  FOREIGN KEY (product_id)
                                      REFERENCES product (product_id)
                                      ON DELETE RESTRICT,
                              CONSTRAINT ck_auction_room_reserve_price
                                  CHECK (reserve_price > 0),
                              CONSTRAINT ck_auction_room_duration
                                  CHECK (duration_minutes > 0),
                              CONSTRAINT ck_auction_room_start_type
                                  CHECK (start_type IN ('IMMEDIATE', 'SCHEDULED')),
                              CONSTRAINT ck_auction_room_schedule
                                  CHECK (
                                      (start_type = 'IMMEDIATE' AND scheduled_at IS NULL)
                                          OR
                                      (start_type = 'SCHEDULED' AND scheduled_at IS NOT NULL)
                                      ),
                              CONSTRAINT ck_auction_room_extension_count
                                  CHECK (extension_count BETWEEN 0 AND 3),
                              CONSTRAINT ck_auction_room_time_order
                                  CHECK (
                                      started_at IS NULL
                                          OR ended_at IS NULL
                                          OR ended_at >= started_at
                                      )
);

CREATE TRIGGER trg_auction_room_updated_at
    BEFORE UPDATE ON auction_room
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX idx_auction_room_status_schedule
    ON auction_room (status, scheduled_at);

CREATE UNIQUE INDEX uq_auction_room_openvidu_session
    ON auction_room (openvidu_session_id)
    WHERE openvidu_session_id IS NOT NULL;

