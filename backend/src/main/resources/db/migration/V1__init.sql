CREATE TABLE report (
                        report_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        reporter_member_id      BIGINT NOT NULL,
                        target_type             VARCHAR(30) NOT NULL,
                        reported_member_id      BIGINT,
                        auction_room_id         BIGINT,
                        chat_message_id         BIGINT,
                        deal_id                 BIGINT,
                        reason_code             VARCHAR(40) NOT NULL,
                        description             TEXT,
                        status                  VARCHAR(20) NOT NULL,
                        processed_by_member_id  BIGINT,
                        resolution_note         TEXT,
                        created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        processed_at            TIMESTAMPTZ,

                        CONSTRAINT fk_report_reporter
                            FOREIGN KEY (reporter_member_id)
                                REFERENCES member (member_id)
                                ON DELETE RESTRICT,
                        CONSTRAINT fk_report_reported_member
                            FOREIGN KEY (reported_member_id)
                                REFERENCES member (member_id)
                                ON DELETE RESTRICT,
                        CONSTRAINT fk_report_auction_room
                            FOREIGN KEY (auction_room_id)
                                REFERENCES auction_room (auction_room_id)
                                ON DELETE RESTRICT,
                        CONSTRAINT fk_report_chat_message
                            FOREIGN KEY (chat_message_id)
                                REFERENCES chat_message (chat_message_id)
                                ON DELETE RESTRICT,
                        CONSTRAINT fk_report_deal
                            FOREIGN KEY (deal_id)
                                REFERENCES deal (deal_id)
                                ON DELETE RESTRICT,
                        CONSTRAINT fk_report_processor
                            FOREIGN KEY (processed_by_member_id)
                                REFERENCES member (member_id)
                                ON DELETE SET NULL,
                        CONSTRAINT ck_report_target_count
                            CHECK (
                                num_nonnulls(
                                        reported_member_id,
                                        auction_room_id,
                                        chat_message_id,
                                        deal_id
                                ) = 1
                                ),
                        CONSTRAINT ck_report_target_type
                            CHECK (
                                (target_type = 'MEMBER'
                                    AND reported_member_id IS NOT NULL
                                    AND auction_room_id IS NULL
                                    AND chat_message_id IS NULL
                                    AND deal_id IS NULL)
                                    OR
                                (target_type = 'AUCTION_ROOM'
                                    AND reported_member_id IS NULL
                                    AND auction_room_id IS NOT NULL
                                    AND chat_message_id IS NULL
                                    AND deal_id IS NULL)
                                    OR
                                (target_type = 'CHAT_MESSAGE'
                                    AND reported_member_id IS NULL
                                    AND auction_room_id IS NULL
                                    AND chat_message_id IS NOT NULL
                                    AND deal_id IS NULL)
                                    OR
                                (target_type = 'DEAL'
                                    AND reported_member_id IS NULL
                                    AND auction_room_id IS NULL
                                    AND chat_message_id IS NULL
                                    AND deal_id IS NOT NULL)
                                ),
                        CONSTRAINT ck_report_processing
                            CHECK (
                                (processed_at IS NULL)
                                    OR
                                (processed_by_member_id IS NOT NULL AND processed_at >= created_at)
                                )
);

CREATE INDEX idx_report_reporter_history
    ON report (reporter_member_id, created_at DESC);

CREATE INDEX idx_report_status_created
    ON report (status, created_at);

CREATE INDEX idx_report_reported_member
    ON report (reported_member_id, created_at DESC)
    WHERE reported_member_id IS NOT NULL;

CREATE INDEX idx_report_auction_room
    ON report (auction_room_id, created_at DESC)
    WHERE auction_room_id IS NOT NULL;

CREATE INDEX idx_report_chat_message
    ON report (chat_message_id, created_at DESC)
    WHERE chat_message_id IS NOT NULL;

CREATE INDEX idx_report_deal
    ON report (deal_id, created_at DESC)
    WHERE deal_id IS NOT NULL;

