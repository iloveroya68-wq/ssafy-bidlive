-- AI-04 상품 검열 이력(감사용).
--
-- product.moderation_status / product_image.moderation_status 는 등록 차단 상태를 담는 컬럼이며
-- 이 API는 등록을 직접 막지 않으므로 건드리지 않는다. 등록 흐름이 생기면 그 쪽에서 이 이력을
-- 참조해 상태를 정한다.
--
-- content_hash 는 같은 콘텐츠 재요청에서 AI 호출을 건너뛰기 위한 캐시 키다. 이력은 감사 기록이라
-- 덮어쓰지 않고 매 판정을 새 행으로 남기며, 조회는 가장 최근 확정 판정 하나만 사용한다.

CREATE TABLE product_inspection (
                                    product_inspection_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    requester_member_id    BIGINT NOT NULL,
                                    content_hash           CHAR(64) NOT NULL,
                                    verdict                VARCHAR(20) NOT NULL,
                                    detail                 JSONB NOT NULL,
                                    inspected_at           TIMESTAMPTZ NOT NULL,
                                    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT fk_product_inspection_requester
                                        FOREIGN KEY (requester_member_id)
                                            REFERENCES member (member_id)
                                            ON DELETE RESTRICT,
                                    CONSTRAINT ck_product_inspection_verdict
                                        CHECK (verdict IN ('PASSED', 'NEEDS_REVIEW', 'REJECTED'))
);

-- 확정 판정만 캐시로 재사용하므로 보류 기록은 색인에서 제외한다.
CREATE INDEX idx_product_inspection_reusable
    ON product_inspection (content_hash, inspected_at DESC)
    WHERE verdict <> 'NEEDS_REVIEW';

CREATE INDEX idx_product_inspection_requester
    ON product_inspection (requester_member_id, inspected_at DESC);
