CREATE TABLE prediction_leaderboard (
                                        prediction_leaderboard_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        member_id                  BIGINT NOT NULL,
                                        ranking_date               DATE NOT NULL,
                                        rank_no                    INT NOT NULL,
                                        score                      BIGINT NOT NULL,
                                        prediction_count           INT NOT NULL,
                                        rewarded_count             INT NOT NULL,
                                        lost_count                 INT NOT NULL,
                                        total_stake_amount         BIGINT NOT NULL,
                                        total_payout_amount        BIGINT NOT NULL,
                                        average_error_rate         NUMERIC(10, 6),
                                        best_error_rate            NUMERIC(10, 6),
                                        created_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                        CONSTRAINT fk_prediction_leaderboard_member
                                            FOREIGN KEY (member_id)
                                                REFERENCES member (member_id)
                                                ON DELETE RESTRICT,
                                        CONSTRAINT uq_prediction_leaderboard_member_date
                                            UNIQUE (ranking_date, member_id),
                                        CONSTRAINT uq_prediction_leaderboard_rank_date
                                            UNIQUE (ranking_date, rank_no),
                                        CONSTRAINT ck_prediction_leaderboard_rank
                                            CHECK (rank_no > 0),
                                        CONSTRAINT ck_prediction_leaderboard_score
                                            CHECK (score >= 0),
                                        CONSTRAINT ck_prediction_leaderboard_counts
                                            CHECK (
                                                prediction_count >= 0
                                                    AND rewarded_count >= 0
                                                    AND lost_count >= 0
                                                    AND rewarded_count + lost_count <= prediction_count
                                                ),
                                        CONSTRAINT ck_prediction_leaderboard_amounts
                                            CHECK (
                                                total_stake_amount >= 0
                                                    AND total_payout_amount >= 0
                                                ),
                                        CONSTRAINT ck_prediction_leaderboard_error_rates
                                            CHECK (
                                                (average_error_rate IS NULL OR average_error_rate >= 0)
                                                    AND (best_error_rate IS NULL OR best_error_rate >= 0)
                                                    AND (
                                                    average_error_rate IS NULL
                                                        OR best_error_rate IS NULL
                                                        OR best_error_rate <= average_error_rate
                                                    )
                                                )
);

CREATE INDEX idx_prediction_leaderboard_member_history
    ON prediction_leaderboard (member_id, ranking_date DESC);

CREATE INDEX idx_prediction_leaderboard_date_score
    ON prediction_leaderboard (
                               ranking_date DESC,
                               score DESC,
                               average_error_rate ASC,
                               member_id
        );

