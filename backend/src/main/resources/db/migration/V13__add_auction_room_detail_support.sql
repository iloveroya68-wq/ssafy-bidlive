ALTER TABLE auction_room
    ADD COLUMN visibility VARCHAR(20) NOT NULL DEFAULT 'PUBLIC',
    ADD COLUMN deleted_at TIMESTAMPTZ,
    ADD CONSTRAINT ck_auction_room_visibility
        CHECK (visibility IN ('PUBLIC', 'PRIVATE'));

CREATE INDEX idx_auction_room_public_detail
    ON auction_room (auction_room_id)
    WHERE visibility = 'PUBLIC' AND deleted_at IS NULL;

CREATE TABLE auction_room_notification_subscription (
    auction_room_notification_subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_room_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_auction_room_notification_room
        FOREIGN KEY (auction_room_id)
            REFERENCES auction_room (auction_room_id)
            ON DELETE CASCADE,
    CONSTRAINT fk_auction_room_notification_member
        FOREIGN KEY (member_id)
            REFERENCES member (member_id)
            ON DELETE CASCADE,
    CONSTRAINT uq_auction_room_notification_member
        UNIQUE (auction_room_id, member_id)
);

CREATE TRIGGER trg_auction_room_notification_updated_at
    BEFORE UPDATE ON auction_room_notification_subscription
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX idx_auction_room_notification_active
    ON auction_room_notification_subscription (auction_room_id, member_id)
    WHERE is_active = TRUE;
