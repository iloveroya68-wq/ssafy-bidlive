-- BidLive live auction platform schema
-- Target DBMS: PostgreSQL 14+
-- Source: 경매 플랫폼 ERD.docx
-- Encoding: UTF-8
--
-- Important application-level invariants that ordinary foreign keys do not fully enforce:
-- 1. A member is created together with exactly one Kakao social_account.
-- 2. Each member owns exactly one TRADE wallet and one BETTING wallet.
-- 3. BIDDER participants may create bid rows only; PREDICTOR participants may create one prediction only.
-- 4. auction_result.winner_participant_id and winning_bid_id must belong to the same auction_room.
-- 5. prediction_result.auction_result_id must reference the result of the prediction's auction_room.
-- 6. deal seller/buyer must match the product seller and auction winner.
-- 7. trade_point_ledger must reference a TRADE wallet; betting_point_ledger must reference a BETTING wallet.
-- 8. Ledger rows are append-only. Do not UPDATE or DELETE ledger history.


-- =========================================================
-- Common updated_at trigger
-- =========================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$;

-- =========================================================
-- Member / OAuth
-- =========================================================

CREATE TABLE member (
                        member_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nickname       VARCHAR(30) UNIQUE,
                        role           VARCHAR(20) NOT NULL DEFAULT 'USER',
                        status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                        created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        withdrawn_at   TIMESTAMPTZ,

                        CONSTRAINT ck_member_role
                            CHECK (role IN ('USER', 'ADMIN')),
                        CONSTRAINT ck_member_status
                            CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
                        CONSTRAINT ck_member_withdrawn_at
                            CHECK (
                                (status = 'WITHDRAWN' AND withdrawn_at IS NOT NULL)
                                    OR
                                (status <> 'WITHDRAWN' AND withdrawn_at IS NULL)
                                )
);

CREATE TRIGGER trg_member_updated_at
    BEFORE UPDATE ON member
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TABLE social_account (
                                social_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                member_id         BIGINT NOT NULL,
                                provider          VARCHAR(20) NOT NULL DEFAULT 'KAKAO',
                                provider_user_id  VARCHAR(255) NOT NULL,
                                email             VARCHAR(320),
                                provider_nickname VARCHAR(100),
                                profile_image_url VARCHAR(2048),
                                created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_social_account_member
                                    FOREIGN KEY (member_id)
                                        REFERENCES member (member_id)
                                        ON DELETE CASCADE,
                                CONSTRAINT uq_social_account_provider_user
                                    UNIQUE (provider, provider_user_id),
                                CONSTRAINT uq_social_account_member_provider
                                    UNIQUE (member_id, provider),
                                CONSTRAINT ck_social_account_provider
                                    CHECK (provider = 'KAKAO')
);

CREATE INDEX idx_social_account_member
    ON social_account (member_id);

