-- LIVE-06 낙찰 스냅샷 메타 기록.
--
-- deal.snapshot_image_url에도 스냅샷 URL 컬럼이 있으나 deal 테이블은 deal 도메인이 소유하고
-- 해당 도메인 구현이 아직 없다. 또한 이 API의 계약은 dealId가 아니라 auctionId 기준이므로
-- media 도메인이 자체 테이블로 보관한다. deal 도메인 구현 후 소유 위치를 정리해야 한다.
--
-- auction_id에는 외래키를 두지 않는다. 경매 존재 여부 검증은 auction 도메인이 구현할
-- AuctionSnapshotVerifier의 책임이며, 외래키로 중복 강제하면 그 검증이 붙기 전에는 404 대신
-- 제약 위반 오류가 노출된다.

CREATE TABLE live_snapshot (
                               live_snapshot_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               room_id           VARCHAR(100) NOT NULL,
                               auction_id        BIGINT NOT NULL UNIQUE,
                               image_url         VARCHAR(500) NOT NULL,
                               captured_at       TIMESTAMPTZ NOT NULL,
                               created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT ck_live_snapshot_room_id
                                   CHECK (length(btrim(room_id)) > 0),
                               CONSTRAINT ck_live_snapshot_image_url
                                   CHECK (length(btrim(image_url)) > 0)
);

CREATE TRIGGER trg_live_snapshot_updated_at
    BEFORE UPDATE ON live_snapshot
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX idx_live_snapshot_room
    ON live_snapshot (room_id);
