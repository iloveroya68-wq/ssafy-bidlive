CREATE TABLE settlement_account (
    settlement_account_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id              BIGINT NOT NULL UNIQUE,
    bank_code              VARCHAR(3) NOT NULL,
    masked_account_number  VARCHAR(50) NOT NULL,
    account_holder_name    VARCHAR(50) NOT NULL,
    verified               BOOLEAN NOT NULL DEFAULT FALSE,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_settlement_account_member
        FOREIGN KEY (member_id)
            REFERENCES member (member_id)
            ON DELETE RESTRICT,
    CONSTRAINT ck_settlement_account_bank_code
        CHECK (bank_code IN ('004', '088', '020', '081', '090', '092')),
    CONSTRAINT ck_settlement_account_masked_number
        CHECK (length(btrim(masked_account_number)) > 0),
    CONSTRAINT ck_settlement_account_holder_name
        CHECK (length(btrim(account_holder_name)) > 0)
);

CREATE TRIGGER trg_settlement_account_updated_at
    BEFORE UPDATE ON settlement_account
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();
