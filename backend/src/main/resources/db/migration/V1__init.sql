                               address_submitted_at   TIMESTAMPTZ,
                               shipped_at             TIMESTAMPTZ,
                               received_confirmed_at  TIMESTAMPTZ,
                               auto_confirm_at        TIMESTAMPTZ,
                               updated_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_deal_shipping_deal
                                   FOREIGN KEY (deal_id)
                                       REFERENCES deal (deal_id)
                                       ON DELETE CASCADE,
                               CONSTRAINT ck_deal_shipping_time_order
                                   CHECK (
                                       (address_submitted_at IS NULL OR shipped_at IS NULL OR shipped_at >= address_submitted_at)
                                           AND
                                       (shipped_at IS NULL OR received_confirmed_at IS NULL OR received_confirmed_at >= shipped_at)
                                       )
);

CREATE TRIGGER trg_deal_shipping_updated_at
    BEFORE UPDATE ON deal_shipping
