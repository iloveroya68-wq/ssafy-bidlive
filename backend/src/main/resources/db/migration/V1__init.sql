CREATE TABLE terms (
                       terms_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       terms_type    VARCHAR(30) NOT NULL,
                       version       VARCHAR(20) NOT NULL,
                       title         VARCHAR(100) NOT NULL,
                       content       TEXT NOT NULL,
                       is_required   BOOLEAN NOT NULL DEFAULT TRUE,
                       is_active     BOOLEAN NOT NULL DEFAULT TRUE,
                       effective_at  TIMESTAMPTZ NOT NULL,
                       created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT uq_terms_type_version
                           UNIQUE (terms_type, version),
                       CONSTRAINT ck_terms_title_not_blank
                           CHECK (length(btrim(title)) > 0),
                       CONSTRAINT ck_terms_content_not_blank
                           CHECK (length(btrim(content)) > 0)
);

CREATE INDEX idx_terms_active_effective
    ON terms (is_active, effective_at DESC);

CREATE TABLE member_terms_agreement (
                                        member_terms_agreement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        member_id                  BIGINT NOT NULL,
                                        terms_id                   BIGINT NOT NULL,
                                        is_agreed                  BOOLEAN NOT NULL,
                                        agreed_at                  TIMESTAMPTZ,
                                        withdrawn_at               TIMESTAMPTZ,
                                        created_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                        updated_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                        CONSTRAINT fk_member_terms_agreement_member
                                            FOREIGN KEY (member_id)
                                                REFERENCES member (member_id)
                                                ON DELETE RESTRICT,
                                        CONSTRAINT fk_member_terms_agreement_terms
                                            FOREIGN KEY (terms_id)
                                                REFERENCES terms (terms_id)
                                                ON DELETE RESTRICT,
                                        CONSTRAINT uq_member_terms_agreement
                                            UNIQUE (member_id, terms_id),
                                        CONSTRAINT ck_member_terms_agreement_state
                                            CHECK (
                                                (
                                                    is_agreed = TRUE
                                                        AND agreed_at IS NOT NULL
                                                        AND withdrawn_at IS NULL
                                                    )
                                                    OR
                                                (
                                                    is_agreed = FALSE
                                                        AND (
                                                        agreed_at IS NULL
                                                            OR withdrawn_at IS NOT NULL
                                                        )
                                                    )
                                                ),
                                        CONSTRAINT ck_member_terms_agreement_time_order
                                            CHECK (
                                                withdrawn_at IS NULL
                                                    OR agreed_at IS NULL
                                                    OR withdrawn_at >= agreed_at
                                                )
);

CREATE TRIGGER trg_member_terms_agreement_updated_at
    BEFORE UPDATE ON member_terms_agreement
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX idx_member_terms_agreement_member
    ON member_terms_agreement (member_id, created_at DESC);

CREATE INDEX idx_member_terms_agreement_terms
    ON member_terms_agreement (terms_id, is_agreed);

